"""Where uploaded files live.

`LocalMediaStorage` writes to a folder and the app serves it under /api/media. That is right for development and a single
server. On hosts with an ephemeral disk (e.g. Render's free tier) uploads vanish on redeploy; swap in an object-storage
implementation with the same three methods (see docs/ROADMAP.md, P7) when that matters.
"""

from __future__ import annotations

import uuid
from pathlib import Path
from typing import Protocol

from fastapi import Request


class MediaStorage(Protocol):
    def save(self, data: bytes, ext: str) -> str: ...
    def delete(self, key: str) -> None: ...
    def url(self, key: str) -> str: ...


class LocalMediaStorage:
    def __init__(self, root: Path, url_prefix: str = "/api/media"):
        self.root = root
        self.url_prefix = url_prefix.rstrip("/")
        self.root.mkdir(parents=True, exist_ok=True)

    def save(self, data: bytes, ext: str) -> str:
        key = f"{uuid.uuid4().hex}{ext}"  # random name: the uploader's file name is never trusted or kept
        (self.root / key).write_bytes(data)
        return key

    def delete(self, key: str) -> None:
        # keys are generated by save(); still refuse anything that is not a bare file name
        if key and Path(key).name == key:
            (self.root / key).unlink(missing_ok=True)

    def url(self, key: str) -> str:
        return f"{self.url_prefix}/{key}"


def sniff_image_ext(data: bytes) -> str | None:
    """Identify JPEG / PNG / WebP from the file's first bytes. The declared content type is not trusted."""
    if data.startswith(b"\xff\xd8\xff"):
        return ".jpg"
    if data.startswith(b"\x89PNG\r\n\x1a\n"):
        return ".png"
    if data[:4] == b"RIFF" and data[8:12] == b"WEBP":
        return ".webp"
    return None


def get_storage(request: Request) -> MediaStorage:
    return request.app.state.storage
